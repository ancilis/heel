function loadRegistry(constants, now) {
    let doc;
    try {
        const stat = fs.lstatSync(constants.registryPath);
        want(stat.isFile() && !stat.isSymbolicLink());
        want(stat.uid === constants.registryOwner);
        want((stat.mode & 0o022) === 0);
        want(stat.size >= 2 && stat.size <= MAX_REGISTRY_BYTES);
        const raw = fs.readFileSync(constants.registryPath);
        want(raw.length === stat.size);
        doc = parseJson(decodeUtf8(new Uint8Array(raw.buffer, raw.byteOffset, raw.length)));
    } catch (e) {
        if (e instanceof Refusal && e.status === 503) throw e;
        refuse(503, 'registry');
    }
    checkRegistry(doc, constants);
    if (doc.expires_at_ms <= now) refuse(503, 'registry_expired');
    if (typeof ngx !== 'undefined' && ngx.shared && ngx.shared.heel_registry) {
        const zone = ngx.shared.heel_registry;
        const key = 'generation:' + doc.host_boot_epoch;
        const seen = zone.get(key);
        if (seen !== undefined && doc.config_generation < seen) refuse(503, 'registry_stale');
        if (seen === undefined || doc.config_generation > seen) zone.set(key, doc.config_generation);
    }
    return doc;
}

function slotForListener(registry, listener, address, port, peer) {
    if (typeof listener !== 'string' || listener.indexOf('slot:') !== 0) refuse(403, 'listener');
    const id = listener.slice(5);
    const slot = registry.slots.find((item) => item.slot_id === id);
    if (slot === undefined) refuse(403, 'slot_unknown');
    if (slot.listener.address !== address || slot.listener.port !== port) refuse(403, 'listener');
    if (slot.peer !== peer) refuse(403, 'peer');
    return slot;
}

