// Request line, target and raw headers. The original request line is authoritative; nginx's
// normalized $uri must equal it exactly.

function requestTarget(r, methods) {
    const line = r.variables.request;
    if (typeof line !== 'string' || line.length > MAX_TARGET_BYTES + 32) refuse(400, 'request_line');
    const match = RE.requestLine.exec(line);
    if (match === null) refuse(400, 'request_line');
    const method = match[1];
    const target = match[2];
    if (methods.indexOf(method) < 0 || method !== r.method) refuse(405, 'method');
    if (target.length > MAX_TARGET_BYTES || !RE.target.test(target)) refuse(400, 'target');
    const args = r.variables.args;
    if (r.variables.request_uri !== target || r.uri !== target || (args !== undefined && args !== '')) refuse(400, 'target');
    if (r.httpVersion !== '1.1') refuse(400, 'version');
    return { method: method, target: target };
}

function rawHeaders(r) {
    const raw = r.rawHeadersIn;
    if (!Array.isArray(raw) || raw.length > MAX_HEADER_FIELDS) refuse(400, 'header_count');
    const fields = Object.create(null);
    let total = 0;
    for (const pair of raw) {
        const name = pair[0];
        const value = pair[1];
        if (typeof name !== 'string' || typeof value !== 'string') refuse(400, 'header_form');
        if (!RE.headerName.test(name) || !RE.headerValue.test(value)) refuse(400, 'header_form');
        const size = name.length + value.length + 4;
        if (size > MAX_HEADER_FIELD_BYTES) refuse(400, 'header_size');
        total += size;
        const key = name.toLowerCase();
        if (Object.prototype.hasOwnProperty.call(fields, key)) refuse(400, 'header_duplicate');
        fields[key] = value;
    }
    if (total > MAX_HEADER_BYTES) refuse(400, 'header_size');
    return fields;
}

function onlyHeaders(fields, required, optional) {
    for (const name of required) {
        if (!Object.prototype.hasOwnProperty.call(fields, name)) refuse(400, 'header_set');
    }
    for (const name of Object.keys(fields)) {
        if (required.indexOf(name) < 0 && optional.indexOf(name) < 0) refuse(400, 'header_set');
    }
}

function requireHost(r, fields, host) {
    if (fields.host !== host) refuse(421, 'host');
    if (r.variables.ssl_server_name !== host) refuse(421, 'sni');
}

function declaredLength(fields, cap) {
    const value = fields['content-length'];
    if (value === undefined || !RE.length.test(value)) refuse(400, 'length');
    const length = Number(value);
    if (length > cap) refuse(413, 'length');
    return length;
}

function decimalHeader(value, minimum) {
    if (typeof value !== 'string' || !RE.decimal.test(value)) refuse(400, 'proof_format');
    const number = Number(value);
    if (!(number <= SAFE_INT) || number < minimum) refuse(400, 'proof_format');
    return number;
}

