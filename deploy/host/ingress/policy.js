// Runner listener handlers.

function runnerRequest(r, constants, now, bodyBytes) {
    const registry = loadRegistry(constants, now);
    const slot = slotForListener(registry, r.variables.heel_listener, r.variables.server_addr, Number(r.variables.server_port), r.remoteAddress);
    const request = requestTarget(r, ['POST']);
    const matched = runnerRoute(request.target);
    const fields = rawHeaders(r);
    const required = ['host', 'content-length', 'content-type'].concat(matched.route.proof || []);
    onlyHeaders(fields, required, ['accept']);
    requireHost(r, fields, constants.host);
    if (fields['content-type'] !== 'application/json') refuse(415, 'content_type');
    if (fields.accept !== undefined && fields.accept !== 'application/json') refuse(400, 'accept');
    const length = declaredLength(fields, matched.route.cap);
    const pre = runnerPrecheck(slot, matched, fields, now);
    const result = { registry: registry, slot: slot, target: request.target, fields: fields, length: length, pre: pre };
    if (bodyBytes !== undefined) checkRunnerBody(result, bodyBytes);
    return result;
}

function checkRunnerBody(request, bytes) {
    if (bytes.length !== request.length) refuse(400, 'length');
    const text = decodeUtf8(bytes);
    const body = request.pre.kind === 'rotation_poll' ? null : parseJson(text);
    runnerBodyCheck(request.slot, request.pre, body, text);
}

function bodyBytesOf(buffer) {
    if (buffer === undefined || buffer === null) return new Uint8Array(0);
    return new Uint8Array(buffer.buffer ? buffer.buffer : buffer, buffer.byteOffset || 0, buffer.byteLength !== undefined ? buffer.byteLength : buffer.length);
}

function setUpstream(r, request) {
    const f = request.fields;
    r.variables.heel_up_path = request.target;
    r.variables.heel_up_runner_id = f['x-heel-runner-id'] || '';
    r.variables.heel_up_key_id = f['x-heel-runner-key-id'] || '';
    r.variables.heel_up_timestamp = f['x-heel-runner-timestamp-ms'] || '';
    r.variables.heel_up_nonce = f['x-heel-runner-nonce'] || '';
    r.variables.heel_up_sequence = f['x-heel-runner-sequence'] || '';
    r.variables.heel_up_signature = f['x-heel-runner-signature'] || '';
    r.variables.heel_gen = String(request.registry.config_generation);
}

// Total deadlines (H0BTD section 5.1). At expiry the timer sends the fixed refusal, schedules a
// zero-delay timer and throws: njs 1.0.2 turns the exception into NGX_ERROR, which terminates the
// request (upstream connection closed, posted terminate handler), and the zero-delay timer's own
// completion runs the posted requests, so the connection, its limit_conn slot and the JS context
// are released at the deadline. The request's JS context is destroyed with it, so nothing awaited
// here can resume, dispatch or deliver later.
//
// njs deletes a timer's event after its callback returns; clearTimeout() on that timer from the
// callback or from a microtask it runs deletes the event a second time and kills the worker
// (every limit_conn slot it held then leaks); settle() is the only clearTimeout() in this file.
// Fixed refusal at a total deadline. Never clear a timer that has fired.
function deadline(r, ms, status, reason) {
    const d = { fired: false, id: null };
    d.id = setTimeout(() => {
        d.fired = true;
        try { count('expired:' + reason); } catch (e) {}
        try { sendRefusal(r, status, reason); } catch (e) {}
        setTimeout(() => {}, 0);        // flush the posted terminate now (section 3)
        throw new Error('deadline');    // -> NGX_ERROR -> ngx_http_terminate_request
    }, ms);
    return d;
}
function settle(d) { if (!d.fired) clearTimeout(d.id); return d.fired; }

async function runnerAccess(r) {
    const constants = constantsFor(r);
    const started = Date.now();
    r.variables.heel_t0 = String(started);
    r.variables.heel_ok = '';
    try {
        const request = runnerRequest(r, constants, started);
        const d = deadline(r, BODY_READ_MS, 408, 'body_timeout');
        let buffer;
        try { buffer = await r.readRequestArrayBuffer(); } finally { if (settle(d)) return; }
        // Boundary belt: a read that completed in the same tick as the deadline is still late.
        if (Date.now() - started > BODY_READ_MS) refuse(408, 'body_timeout');
        checkRunnerBody(request, bodyBytesOf(buffer));
        setUpstream(r, request);
        // Only after every check above: the positive marker the content handler requires.
        r.variables.heel_ok = '1';
        count('admitted:' + request.pre.kind);
    } catch (e) {
        r.variables.heel_ok = '';
        finishWithError(r, e);
    }
}

const RESPONSE_STATUSES = [200, 201, 204, 400, 401, 403, 404, 405, 408, 409, 410, 413, 415, 422, 429, 500, 502, 503, 504];

function responseHeaders(reply) {
    const raw = reply.rawHeadersOut || [];
    const fields = Object.create(null);
    for (const pair of raw) {
        const key = String(pair[0]).toLowerCase();
        if (Object.prototype.hasOwnProperty.call(fields, key)) refuse(502, 'upstream_header');
        fields[key] = String(pair[1]);
    }
    const forbidden = ['set-cookie', 'location', 'content-encoding', 'transfer-encoding', 'upgrade', 'www-authenticate', 'proxy-authenticate', 'x-accel-redirect', 'x-accel-buffering', 'x-accel-limit-rate', 'x-accel-expires', 'x-accel-charset', 'x-heel-edge-auth', 'trailer'];
    for (const name of forbidden) {
        if (Object.prototype.hasOwnProperty.call(fields, name)) refuse(502, 'upstream_header');
    }
    return fields;
}

function checkRunnerResponse(request, status, fields, contentType, bytes) {
    if (RESPONSE_STATUSES.indexOf(status) < 0) refuse(502, 'upstream_status');
    if (bytes.length > MAX_RESPONSE_BYTES) refuse(502, 'upstream_body');
    const declared = fields['content-length'];
    if (declared !== undefined && (!/^(?:0|[1-9][0-9]{0,6})$/.test(declared) || Number(declared) !== bytes.length)) refuse(502, 'upstream_body');
    const nonce = fields['x-heel-runner-next-nonce'];
    if (nonce !== undefined && !RE.b64x32.test(nonce)) refuse(502, 'upstream_header');
    const retry = fields['retry-after'];
    if (retry !== undefined && (!/^(?:0|[1-9][0-9]{0,2})$/.test(retry) || Number(retry) > 300)) refuse(502, 'upstream_header');
    const pop = request.slot.runner !== null && RUNNER_ROUTES.some((route) => route.kind === request.pre.kind && route.proof === PROOF6);
    if (pop && status >= 200 && status <= 299 && nonce === undefined) refuse(502, 'upstream_header');
    if (status === 204) {
        if (bytes.length !== 0) refuse(502, 'upstream_body');
        return null;
    }
    if (typeof contentType !== 'string' || contentType.split(';')[0].trim().toLowerCase() !== 'application/json') refuse(502, 'upstream_header');
    let body;
    try {
        body = parseJson(decodeUtf8(bytes), true);
    } catch (e) {
        refuse(502, 'upstream_body');
    }
    if (!isObject(body)) refuse(502, 'upstream_body');
    if (status >= 200 && status <= 299) checkReturnedIdentity(request, body);
    return body;
}

function upstreamSame(actual, expected) {
    if (actual !== expected) refuse(502, 'upstream_identity');
}

// Before delivering returned authority, every identity it names must already be in the slot.
function checkReturnedIdentity(request, body) {
    const slot = request.slot;
    const kind = request.pre.kind;
    if (kind === 'pairing_exchange') {
        const invitation = slot.invitation;
        upstreamSame(body.schema_version, 'heel.runner-pairing-pending.v3');
        upstreamSame(body.pairing_id, invitation.pairing_id);
        upstreamSame(body.fingerprint, invitation.expected_fingerprint);
        upstreamSame(body.control_protocol, CONTROL_PROTOCOL);
        upstreamSame(body.status, 'pending');
        return;
    }
    if (kind === 'pairing_activate') {
        const record = request.pre.ids.pairing;
        upstreamSame(body.schema_version, 'heel.runner-pairing-activated.v4');
        upstreamSame(body.workspace_id, slot.workspace_id);
        upstreamSame(body.runner_id, record.runner_id);
        upstreamSame(body.runner_key_id, record.runner_key_id);
        upstreamSame(body.pairing_exchange_digest, record.pairing_exchange_digest);
        upstreamSame(body.control_protocol, CONTROL_PROTOCOL);
        return;
    }
    if (kind === 'rotation_activate') {
        upstreamSame(body.schema_version, 'heel.runner-rotation-activated.v2');
        upstreamSame(body.workspace_id, slot.workspace_id);
        upstreamSame(body.runner_id, slot.runner.runner_id);
        return;
    }
    if (kind === 'claim') {
        const grant = body.grant;
        const projection = body.approval_projection;
        if (!isObject(grant) || !isObject(projection) || !isObject(grant.approval) || !isObject(grant.runner_binding) || !isObject(grant.environment)) refuse(502, 'upstream_identity');
        const run = slot.runs.find((item) => item.run_id === body.run_id && item.state === 'admitted');
        if (run === undefined) refuse(502, 'upstream_identity');
        upstreamSame(grant.run_id, run.run_id);
        upstreamSame(grant.workspace_id, slot.workspace_id);
        upstreamSame(grant.project_id, run.project_id);
        upstreamSame(grant.grant_id, run.grant_id);
        upstreamSame(grant.grant_digest, run.grant_digest);
        upstreamSame(grant.approval.projection_id, run.projection_id);
        upstreamSame(grant.approval.projection_digest, run.approval_projection_digest);
        upstreamSame(grant.approval.manifest_digest, run.manifest_digest);
        upstreamSame(grant.runner_binding.runner_id, slot.runner.runner_id);
        upstreamSame(grant.runner_binding.runner_key_id, slot.runner.runner_key_id);
        upstreamSame(grant.runner_binding.public_key_digest, slot.runner.public_key_digest);
        upstreamSame(projection.projection_id, run.projection_id);
        upstreamSame(projection.projection_digest, run.approval_projection_digest);
        if (!slot.projects.some((p) => p.project_id === run.project_id && p.environment_id === grant.environment.environment_id && p.verification_record_digest === grant.environment.verification_record_digest)) refuse(502, 'upstream_identity');
        return;
    }
    if (kind === 'context_list') {
        if (!Array.isArray(body.contexts)) refuse(502, 'upstream_identity');
        for (const item of body.contexts) {
            if (!isObject(item)) refuse(502, 'upstream_identity');
            const context = slot.contexts.find((c) => c.binding_id === item.binding_id);
            if (context === undefined) refuse(502, 'upstream_identity');
            upstreamSame(item.binding_digest, context.binding_digest);
            upstreamSame(item.project_id, context.project_id);
            upstreamSame(item.environment_id, context.environment_id);
        }
        return;
    }
    if (kind === 'context_claim') {
        const context = request.pre.ids.context;
        const binding = body.context_binding;
        if (!isObject(binding) || !isObject(binding.environment) || !isObject(binding.runner_binding)) refuse(502, 'upstream_identity');
        upstreamSame(binding.binding_id, context.binding_id);
        upstreamSame(binding.workspace_id, slot.workspace_id);
        upstreamSame(binding.project_id, context.project_id);
        upstreamSame(binding.environment.environment_id, context.environment_id);
        upstreamSame(binding.runner_binding.runner_id, slot.runner.runner_id);
        upstreamSame(binding.runner_binding.runner_key_id, slot.runner.runner_key_id);
        return;
    }
    if (kind === 'run_operation' || kind === 'result_projection') {
        if (Object.prototype.hasOwnProperty.call(body, 'run_id')) upstreamSame(body.run_id, request.pre.ids.run.run_id);
        if (Object.prototype.hasOwnProperty.call(body, 'grant_id')) upstreamSame(body.grant_id, request.pre.ids.run.grant_id);
        return;
    }
    // context_submit, resync and aborts carry no new authority for this slot to deliver.
}

async function runnerContent(r) {
    const constants = constantsFor(r);
    let finished = false;
    try {
        if (r.variables.heel_ok !== '1') refuse(403, 'not_admitted');
        const generation = r.variables.heel_gen;
        const started = Number(r.variables.heel_t0);
        const bytes = bodyBytesOf(r.requestBuffer);
        // Recheck the whole request against a fresh snapshot immediately before dispatch.
        const request = runnerRequest(r, constants, Date.now(), bytes);
        if (String(request.registry.config_generation) !== generation) refuse(503, 'generation_changed');
        const remaining = TOTAL_BUDGET_MS - (Date.now() - started);
        if (!(remaining > 0)) refuse(504, 'timeout');
        r.variables.heel_state = 'dispatch';
        const d = deadline(r, remaining, 504, 'timeout');
        let reply;
        try { reply = await r.subrequest(UPSTREAM_PREFIX + request.target, { method: 'POST', body: bytes }); } finally { if (settle(d)) return; }
        r.variables.heel_state = 'done';
        const fields = responseHeaders(reply);
        const status = reply.status;
        const out = bodyBytesOf(reply.responseBuffer);
        checkRunnerResponse(request, status, fields, reply.headersOut['Content-Type'], out);
        // A generation change while the request was upstream withholds any returned authority.
        const after = runnerRequest(r, constants, Date.now(), bytes);
        if (String(after.registry.config_generation) !== generation) refuse(502, 'generation_changed');
        finished = true;
        r.headersOut['Cache-Control'] = 'no-store';
        if (fields['x-heel-runner-next-nonce'] !== undefined) r.headersOut['X-Heel-Runner-Next-Nonce'] = fields['x-heel-runner-next-nonce'];
        if (fields['retry-after'] !== undefined) r.headersOut['Retry-After'] = fields['retry-after'];
        count('forwarded:' + request.pre.kind + ':' + status);
        if (status === 204) {
            r.return(204);
            return;
        }
        r.headersOut['Content-Type'] = 'application/json';
        r.return(status, out);
    } catch (e) {
        r.variables.heel_state = 'done';
        // An error after the response was already sent is ignored (nothing more is written).
        if (finished && !(e instanceof Refusal)) return;
        finishWithError(r, e);
    }
}

// The internal location's edge-secret value: present only for a subrequest whose parent was
// admitted, is dispatching now, and names exactly the admitted path.
function dispatchGate(r) {
    try {
        if (r.parent === undefined || r.parent === null) return '';
        if (r.variables.heel_ok !== '1' || r.variables.heel_state !== 'dispatch') return '';
        if (r.uri !== UPSTREAM_PREFIX + r.variables.heel_up_path) return '';
        if (r.method !== 'POST') return '';
        return r.variables.heel_edge_secret || '';
    } catch (e) {
        return '';
    }
}

