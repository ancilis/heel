// Path, header and phase identities that need no body (checked before the body is read).
function runnerPrecheck(slot, matched, fields, now) {
    const route = matched.route;
    const m = matched.match;
    const result = { kind: route.kind, ids: {} };
    if (route.proof !== null) {
        const runner = runnerOf(slot);
        same(m[1], slot.workspace_id);
        same(m[2], runner.runner_id);
        same(fields['x-heel-runner-id'], runner.runner_id);
        same(fields['x-heel-runner-key-id'], runner.runner_key_id);
        decimalHeader(fields['x-heel-runner-timestamp-ms'], 0);
        if (route.proof === PROOF6) {
            if (!RE.b64x32.test(fields['x-heel-runner-nonce'])) refuse(400, 'proof_format');
            decimalHeader(fields['x-heel-runner-sequence'], 1);
        }
        if (!RE.b64x64.test(fields['x-heel-runner-signature'])) refuse(400, 'proof_format');
        if (route.kind === 'context_claim' || route.kind === 'context_submit') {
            result.ids.context = contextOf(slot, m[3]);
        }
        if (route.kind === 'run_operation' || route.kind === 'result_projection') {
            result.ids.run = runOf(slot, m[3]);
            result.ids.operation = route.kind === 'run_operation' ? m[4] : 'result-projection';
        }
        if (route.kind === 'resync') result.ids.phase = m[3];
        if (route.kind === 'claim' && slot.phase === 'stopping') refuse(403, 'phase');
        return result;
    }
    if (route.kind === 'pairing_exchange') {
        if (slot.phase !== 'invited' || slot.invitation === null) refuse(403, 'phase');
        if (slot.invitation.expires_at_ms <= now) refuse(403, 'expired');
        return result;
    }
    if (route.kind === 'pairing_activate' || route.kind === 'pairing_abort') {
        // Pending, or the retained ceremony of the active pairing (bounded receipt recovery).
        const record = slot.pairing;
        if (record === null || ['pending', 'active', 'rotating', 'stopping'].indexOf(slot.phase) < 0) refuse(403, 'phase');
        same(m[1], record.pairing_id);
        if (record.expires_at_ms <= now) refuse(403, 'expired');
        result.ids.pairing = record;
        return result;
    }
    // Rotation routes: only the one registered rotation of a rotating slot.
    if (slot.phase !== 'rotating' || slot.rotation === null || slot.runner === null) refuse(403, 'phase');
    same(m[1], slot.rotation.rotation_id);
    if (slot.rotation.expires_at_ms <= now) refuse(403, 'expired');
    result.ids.rotation = slot.rotation;
    return result;
}

const RUN_OPERATION_SCHEMA = {
    heartbeat: 'heel.runner-heartbeat-request.v1',
    progress: 'heel.runner-progress-request.v1',
    result: 'heel.runner-result-request.v1',
    'stop-ack': 'heel.runner-stop-ack-request.v1',
};

function checkOperational(projection, slot, run) {
    if (!isObject(projection)) refuse(400, 'body_schema');
    same(projection.run_id, run.run_id);
    same(projection.workspace_id, slot.workspace_id);
    same(projection.project_id, run.project_id);
    same(projection.grant_id, run.grant_id);
    same(projection.grant_digest, run.grant_digest);
    same(projection.approval_projection_digest, run.approval_projection_digest);
    same(projection.manifest_digest, run.manifest_digest);
    same(projection.signing_key_id, slot.runner.runner_key_id);
}

// Small control-envelope checks: exact top-level members and the identity-bearing fields the
// registry can compare. Full schemas, signatures and state stay with the control plane.
function runnerBodyCheck(slot, pre, body, text) {
    const kind = pre.kind;
    if (kind === 'rotation_poll') {
        if (text !== '{}') refuse(400, 'body_schema');
        return;
    }
    if (canonicalText(body) !== text) refuse(400, 'canonical');
    if (!isObject(body)) refuse(400, 'body_schema');
    if (kind === 'pairing_exchange') {
        if (!exactKeys(body, ['schema_version', 'invitation_token', 'public_key_b64', 'pairing_phrase', 'display_name', 'runner_version', 'adapters', 'control_protocol'])) refuse(400, 'body_schema');
        same(body.schema_version, 'heel.runner-pairing-exchange.v3');
        same(body.control_protocol, CONTROL_PROTOCOL);
        if (typeof body.invitation_token !== 'string') refuse(400, 'body_schema');
        same(sha256Hex(body.invitation_token), slot.invitation.token_sha256);
        same(body.public_key_b64, slot.invitation.expected_public_key_b64);
        return;
    }
    if (kind === 'pairing_activate') {
        if (!exactKeys(body, ['schema_version', 'client_activation_nonce_b64', 'signature_b64'])) refuse(400, 'body_schema');
        same(body.schema_version, 'heel.runner-pairing-activate.v3');
        return;
    }
    if (kind === 'pairing_abort') {
        const record = pre.ids.pairing;
        const v1 = ['schema_version', 'pairing_id', 'runner_id', 'pairing_exchange_digest', 'activation_request_digest', 'reason_code', 'signature_b64', 'challenge_expires_at_ms'];
        const v2 = ['schema_version', 'pairing_id', 'runner_id', 'pairing_exchange_digest', 'activation_request_digest', 'reason_code', 'signature_b64', 'activation_challenge_digest'];
        if (exactKeys(body, v1)) same(body.schema_version, 'heel.runner-pairing-activation-abort.v1');
        else if (exactKeys(body, v2)) same(body.schema_version, 'heel.runner-pairing-activation-abort.v2');
        else refuse(400, 'body_schema');
        same(body.pairing_id, record.pairing_id);
        same(body.runner_id, record.runner_id);
        same(body.pairing_exchange_digest, record.pairing_exchange_digest);
        return;
    }
    if (kind === 'rotation_activate') {
        if (!exactKeys(body, ['schema_version', 'signature_b64'])) refuse(400, 'body_schema');
        same(body.schema_version, 'heel.runner-rotation-activate.v2');
        return;
    }
    if (kind === 'rotation_abort') {
        const rotation = pre.ids.rotation;
        if (!exactKeys(body, ['schema_version', 'workspace_id', 'runner_id', 'pairing_id', 'old_runner_key_id', 'new_runner_key_id', 'activation_request_digest', 'activation_challenge_digest', 'challenge_expires_at_ms', 'reason_code', 'old_signature_b64', 'new_signature_b64'])) refuse(400, 'body_schema');
        same(body.schema_version, 'heel.runner-rotation-activation-abort.v1');
        same(body.workspace_id, slot.workspace_id);
        same(body.runner_id, slot.runner.runner_id);
        same(body.pairing_id, rotation.rotation_id);
        same(body.old_runner_key_id, rotation.old_runner_key_id);
        same(body.new_runner_key_id, rotation.new_runner_key_id);
        return;
    }
    if (kind === 'claim') {
        if (!exactKeys(body, ['schema_version'])) refuse(400, 'body_schema');
        same(body.schema_version, 'heel.runner-claim-request.v1');
        return;
    }
    if (kind === 'context_list') {
        if (!exactKeys(body, ['schema_version'])) refuse(400, 'body_schema');
        same(body.schema_version, 'heel.runner-context-list.v1');
        return;
    }
    if (kind === 'context_claim') {
        const context = pre.ids.context;
        if (!exactKeys(body, ['schema_version', 'binding_id', 'binding_digest'])) refuse(400, 'body_schema');
        same(body.schema_version, 'heel.runner-context-claim.v1');
        same(body.binding_id, context.binding_id);
        same(body.binding_digest, context.binding_digest);
        return;
    }
    if (kind === 'context_submit') {
        const context = pre.ids.context;
        if (!exactKeys(body, ['schema_version', 'context_binding_id', 'context_binding_digest', 'approval_projection'])) refuse(400, 'body_schema');
        same(body.schema_version, 'heel.runner-approval-projection-submit.v1');
        same(body.context_binding_id, context.binding_id);
        same(body.context_binding_digest, context.binding_digest);
        const projection = body.approval_projection;
        if (!isObject(projection) || !isObject(projection.environment) || !isObject(projection.runner)) refuse(400, 'body_schema');
        same(projection.workspace_id, slot.workspace_id);
        same(projection.project_id, context.project_id);
        same(projection.environment.environment_id, context.environment_id);
        same(projection.runner.runner_id, slot.runner.runner_id);
        same(projection.runner.runner_key_id, slot.runner.runner_key_id);
        same(projection.signing_key_id, slot.runner.runner_key_id);
        return;
    }
    if (kind === 'run_operation') {
        const run = pre.ids.run;
        if (!exactKeys(body, ['schema_version', 'run_id', 'operational_projection'])) refuse(400, 'body_schema');
        same(body.schema_version, RUN_OPERATION_SCHEMA[pre.ids.operation]);
        same(body.run_id, run.run_id);
        checkOperational(body.operational_projection, slot, run);
        return;
    }
    if (kind === 'result_projection') {
        const run = pre.ids.run;
        if (!exactKeys(body, ['schema_version', 'run_id', 'permit', 'findings_projection'])) refuse(400, 'body_schema');
        same(body.schema_version, 'heel.runner-findings-upload.v1');
        same(body.run_id, run.run_id);
        const permit = body.permit;
        const findings = body.findings_projection;
        if (!isObject(permit) || !isObject(permit.runner_binding) || !isObject(findings)) refuse(400, 'body_schema');
        same(permit.run_id, run.run_id);
        same(permit.workspace_id, slot.workspace_id);
        same(permit.project_id, run.project_id);
        same(permit.grant_id, run.grant_id);
        same(permit.runner_binding.runner_id, slot.runner.runner_id);
        same(permit.runner_binding.runner_key_id, slot.runner.runner_key_id);
        same(findings.run_id, run.run_id);
        same(findings.workspace_id, slot.workspace_id);
        same(findings.project_id, run.project_id);
        same(findings.grant_id, run.grant_id);
        same(findings.grant_digest, run.grant_digest);
        same(findings.approval_projection_digest, run.approval_projection_digest);
        same(findings.manifest_digest, run.manifest_digest);
        same(findings.signing_key_id, slot.runner.runner_key_id);
        return;
    }
    if (kind === 'resync') {
        const start = ['schema_version', 'chain', 'client_nonce_b64'];
        const complete = ['schema_version', 'challenge_id', 'chain', 'client_nonce_b64', 'server_challenge_b64', 'generation'];
        if (pre.ids.phase === 'start') {
            if (!exactKeys(body, start)) refuse(400, 'body_schema');
            same(body.schema_version, 'heel.runner-resync-start.v2');
        } else {
            if (!exactKeys(body, complete)) refuse(400, 'body_schema');
            same(body.schema_version, 'heel.runner-resync-complete.v2');
        }
        const chain = body.chain;
        if (!exactKeys(chain, ['operation', 'run_id'])) refuse(400, 'body_schema');
        if (chain.operation === 'claim') {
            same(chain.run_id, null);
        } else if (['heartbeat', 'progress', 'result', 'stop-ack'].indexOf(chain.operation) >= 0) {
            runOf(slot, chain.run_id);
        } else {
            refuse(400, 'body_schema');
        }
        return;
    }
    refuse(404, 'route');
}

