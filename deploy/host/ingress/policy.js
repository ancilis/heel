// Returns the route whose methods include `method`, or a 404/405 refusal; first match wins so the
// classes resolve in the Worker's own order.
function managementRoute(method, target) {
    let pathMatched = false;
    for (const route of MANAGEMENT_ROUTES) {
        if (route.re.test(target)) {
            pathMatched = true;
            if (route.methods.indexOf(method) >= 0) return route;
        }
    }
    refuse(pathMatched ? 405 : 404, 'route');
}

const SESSION_COOKIE = /^heel_session=[A-Za-z0-9_-]+$/;
const API_KEY = /^Bearer heel_sk_[A-Za-z0-9_-]+$/;
const DEVICE_TOKEN = /^Bearer heel_at_[A-Za-z0-9_-]{43}$/;
const CANARY_IDEMPOTENCY = /^ca1-[0-9a-f]{64}$/;
const FINDINGS_IDEMPOTENCY = /^fs1-[0-9a-f]{64}$/;
const CONTROL_GENERATION = /^(?:0|[1-9][0-9]{0,19})$/;

// The header names each Worker class may carry (besides host, the edge secret, POST framing and a
// transport-generated Connection), as required/optional sets.
function managementHeaderSet(route, method, origin) {
    const c = route.headerClass;
    if (c === 'proof6') return { required: PROOF6, optional: [] };
    if (c === 'proof4') return { required: PROOF4, optional: [] };
    if (c === 'anonymous') return { required: [], optional: [] };
    if (c === 'anonymous_client_key') return { required: ['x-heel-client-key'], optional: [] };
    if (c === 'session_origin') return { required: ['cookie', 'origin', 'x-heel-internal-origin'], optional: [] };
    if (c === 'owner' || c === 'owner_approve' || c === 'owner_stop') {
        if (method !== 'POST') return { required: ['cookie'], optional: [] };
        const required = ['cookie', 'origin', 'x-heel-internal-origin'];
        if (c === 'owner_approve') required.push('idempotency-key', 'if-heel-control-generation');
        if (c === 'owner_stop') required.push('if-heel-control-generation');
        return { required: required, optional: [] };
    }
    if (c === 'credentials') return { required: [], optional: ['cookie', 'authorization'] };
    if (c === 'credentials_idempotent') return { required: ['idempotency-key'], optional: ['cookie', 'authorization'] };
    refuse(400, 'route');
}

function managementRequest(r, constants, now) {
    const registry = loadRegistry(constants, now);
    if (r.variables.heel_listener !== 'management') refuse(403, 'listener');
    if (r.variables.server_addr + ':' + r.variables.server_port !== constants.management) refuse(403, 'listener');
    if (r.remoteAddress !== registry.management.peer) refuse(403, 'peer');
    const request = requestTarget(r, ['GET', 'POST', 'DELETE']);
    const route = managementRoute(request.method, request.target);
    const fields = rawHeaders(r);
    // Exactly the one Worker edge secret, before any other header question.
    const expected = r.variables.heel_edge_secret;
    if (typeof expected !== 'string' || expected.length < 43 || fields['x-heel-edge-auth'] !== expected) refuse(403, 'edge_secret');
    // A transport-generated singleton connection token is consumed here and never forwarded.
    if (fields.connection !== undefined) {
        if (fields.connection !== 'close' && fields.connection !== 'keep-alive') refuse(400, 'header_set');
        delete fields.connection;
    }
    const classSet = managementHeaderSet(route, request.method, constants);
    const framing = request.method === 'POST' ? ['content-length', 'content-type', 'content-encoding'] : [];
    onlyHeaders(fields, ['host', 'x-heel-edge-auth'].concat(framing, classSet.required), classSet.optional);
    requireHost(r, fields, constants.host);
    if (request.method === 'POST') {
        if (fields['content-type'] !== 'application/json') refuse(415, 'content_type');
        if (fields['content-encoding'] !== 'identity') refuse(400, 'content_encoding');
        declaredLength(fields, route.cap);
    }
    const origin = 'https://' + constants.host;
    if (fields.cookie !== undefined && !SESSION_COOKIE.test(fields.cookie)) refuse(400, 'credentials');
    if (fields.authorization !== undefined && !(API_KEY.test(fields.authorization) || DEVICE_TOKEN.test(fields.authorization))) refuse(400, 'credentials');
    if (fields.cookie !== undefined && fields.authorization !== undefined) refuse(400, 'credentials');
    if (fields.origin !== undefined && fields.origin !== origin) refuse(403, 'origin');
    if (fields['x-heel-internal-origin'] !== undefined && fields['x-heel-internal-origin'] !== 'same-origin') refuse(403, 'origin');
    if (fields['x-heel-client-key'] !== undefined && !RE.hex64.test(fields['x-heel-client-key'])) refuse(400, 'client_key');
    if (fields['idempotency-key'] !== undefined) {
        const pattern = route.headerClass === 'credentials_idempotent' ? FINDINGS_IDEMPOTENCY : CANARY_IDEMPOTENCY;
        if (!pattern.test(fields['idempotency-key'])) refuse(400, 'idempotency');
    }
    if (fields['if-heel-control-generation'] !== undefined && !CONTROL_GENERATION.test(fields['if-heel-control-generation'])) refuse(400, 'control_generation');
    if (route.headerClass === 'proof6' || route.headerClass === 'proof4') {
        decimalHeader(fields['x-heel-runner-timestamp-ms'], 0);
        if (!RE.rid.test(fields['x-heel-runner-id']) || !RE.keyId.test(fields['x-heel-runner-key-id'])) refuse(400, 'proof_format');
        if (route.headerClass === 'proof6') {
            if (!RE.b64x32.test(fields['x-heel-runner-nonce'])) refuse(400, 'proof_format');
            decimalHeader(fields['x-heel-runner-sequence'], 1);
        }
        if (!RE.b64x64.test(fields['x-heel-runner-signature'])) refuse(400, 'proof_format');
    }
    return { route: route, method: request.method, target: request.target, fields: fields };
}

async function managementAccess(r) {
    try {
        const started = Date.now();
        const request = managementRequest(r, constantsFor(r), started);
        if (request.method === 'POST') {
            // The body is read here under the same total deadline; proxy_pass then forwards the
            // already-read (preserved) body, never reading the client again.
            const d = deadline(r, BODY_READ_MS, 408, 'body_timeout');
            try { await r.readRequestArrayBuffer(); } finally { if (settle(d)) return; }
            if (Date.now() - started > BODY_READ_MS) refuse(408, 'body_timeout');
        }
        const f = request.fields;
        r.variables.heel_m_cookie = f.cookie || '';
        r.variables.heel_m_authorization = f.authorization || '';
        r.variables.heel_m_origin = f.origin || '';
        r.variables.heel_m_internal_origin = f['x-heel-internal-origin'] || '';
        r.variables.heel_m_client_key = f['x-heel-client-key'] || '';
        r.variables.heel_m_idempotency = f['idempotency-key'] || '';
        r.variables.heel_m_generation = f['if-heel-control-generation'] || '';
        r.variables.heel_m_content_type = f['content-type'] || '';
        r.variables.heel_m_content_encoding = f['content-encoding'] || '';
        r.variables.heel_up_runner_id = f['x-heel-runner-id'] || '';
        r.variables.heel_up_key_id = f['x-heel-runner-key-id'] || '';
        r.variables.heel_up_timestamp = f['x-heel-runner-timestamp-ms'] || '';
        r.variables.heel_up_nonce = f['x-heel-runner-nonce'] || '';
        r.variables.heel_up_sequence = f['x-heel-runner-sequence'] || '';
        r.variables.heel_up_signature = f['x-heel-runner-signature'] || '';
        r.variables.heel_m_edge = f['x-heel-edge-auth'];
        r.variables.heel_ok = '1';
        count('admitted:management:' + request.route.name);
    } catch (e) {
        r.variables.heel_ok = '';
        finishWithError(r, e);
    }
}

// The management proxy's edge-secret value: the validated Worker secret, only once admitted.
function managementEdge(r) {
    try {
        if (r.variables.heel_ok !== '1' || r.variables.heel_listener !== 'management') return '';
        return r.variables.heel_m_edge || '';
    } catch (e) {
        return '';
    }
}

// The default server of every TLS listener: a request whose Host names anything but H after a
// handshake for H (nginx re-selects the server by Host) is misdirected, never processed.
function misdirected(r) {
    sendRefusal(r, 421, 'host');
}

// Private ingress-namespace operational endpoint: fixed counter names and integers only.
function counters(r) {
    const result = Object.create(null);
    try {
        const zone = ngx.shared.heel_counters;
        for (const key of zone.keys(1024)) {
            result[key] = zone.get(key);
        }
    } catch (e) {
        r.return(500, '{"error":"counters unavailable"}');
        return;
    }
    r.headersOut['Content-Type'] = 'application/json';
    r.headersOut['Cache-Control'] = 'no-store';
    r.return(200, JSON.stringify(result));
}

