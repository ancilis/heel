class Refusal extends Error {
    constructor(status, reason) {
        super(reason);
        this.status = status;
        this.reason = reason;
    }
}

function refuse(status, reason) {
    throw new Refusal(status, reason);
}

function count(name) {
    try {
        if (typeof ngx !== 'undefined' && ngx.shared && ngx.shared.heel_counters) {
            ngx.shared.heel_counters.incr(name, 1, 0);
        }
    } catch (e) {
        // Counters are evidence only; a full zone never changes a decision.
    }
}

function sendRefusal(r, status, reason) {
    count('refused:' + reason);
    r.headersOut['Content-Type'] = 'application/json';
    r.headersOut['Cache-Control'] = 'no-store';
    r.return(status, '{"error":"ingress refused"}');
}

function finishWithError(r, error) {
    if (error instanceof Refusal) {
        sendRefusal(r, error.status, error.reason);
    } else {
        sendRefusal(r, 500, 'internal');
    }
}

