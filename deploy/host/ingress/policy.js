function checkSlot(slot) {
    want(exactKeys(slot, [
        'slot_id', 'listener', 'peer', 'namespace_id', 'workspace_id', 'phase', 'runner',
        'invitation', 'pairing', 'rotation', 'projects', 'contexts', 'runs',
    ]));
    wantString(slot.slot_id, RE.label);
    checkSocket(slot.listener);
    wantString(slot.peer, RE.ipv4);
    wantString(slot.namespace_id, RE.label);
    wantNullable(slot.workspace_id, (v) => wantString(v, RE.ws));
    want(PHASES.indexOf(slot.phase) >= 0);
    wantNullable(slot.runner, checkRunnerRecord);
    wantNullable(slot.invitation, checkInvitation);
    wantNullable(slot.pairing, checkPairing);
    wantNullable(slot.rotation, checkRotation);
    want(Array.isArray(slot.projects) && slot.projects.length <= MAX_PROJECTS);
    want(Array.isArray(slot.contexts) && slot.contexts.length <= MAX_CONTEXTS);
    want(Array.isArray(slot.runs) && slot.runs.length <= MAX_RUNS);
    const projects = Object.create(null);
    for (const project of slot.projects) {
        want(exactKeys(project, ['project_id', 'environment_id', 'verification_record_digest']));
        wantString(project.project_id, RE.prj);
        wantString(project.environment_id, RE.env);
        wantString(project.verification_record_digest, RE.hex64);
        const key = project.project_id + ' ' + project.environment_id;
        want(!projects[key]);
        projects[key] = true;
    }
    const contexts = Object.create(null);
    for (const context of slot.contexts) {
        want(exactKeys(context, ['binding_id', 'binding_digest', 'project_id', 'environment_id']));
        wantString(context.binding_id, RE.rcb);
        wantString(context.binding_digest, RE.hex64);
        want(projects[context.project_id + ' ' + context.environment_id] === true);
        want(!contexts[context.binding_id]);
        contexts[context.binding_id] = true;
    }
    const runs = Object.create(null);
    let admitted = 0;
    for (const run of slot.runs) {
        want(exactKeys(run, ['run_id', 'project_id', 'grant_id', 'grant_digest', 'projection_id', 'approval_projection_digest', 'manifest_digest', 'state']));
        wantString(run.run_id, RE.crun);
        wantString(run.project_id, RE.prj);
        wantString(run.grant_id, RE.keyId);
        wantString(run.grant_digest, RE.hex64);
        wantString(run.projection_id, RE.keyId);
        wantString(run.approval_projection_digest, RE.hex64);
        wantString(run.manifest_digest, RE.hex64);
        want(run.state === 'admitted' || run.state === 'retained');
        if (run.state === 'admitted') admitted++;
        want(!runs[run.run_id]);
        runs[run.run_id] = true;
        want(slot.projects.some((p) => p.project_id === run.project_id));
    }
    want(admitted <= 1);
    // Closed phase shapes: each phase names exactly the ceremony records it may use.
    const phase = slot.phase;
    if (phase === 'closed' || phase === 'retired') {
        want(slot.runner === null && slot.invitation === null && slot.pairing === null && slot.rotation === null);
        want(slot.contexts.length === 0 && slot.runs.length === 0);
    } else if (phase === 'invited') {
        want(slot.workspace_id !== null && slot.invitation !== null && slot.runner === null);
        want(slot.pairing === null && slot.rotation === null && slot.contexts.length === 0 && slot.runs.length === 0);
    } else if (phase === 'pending') {
        want(slot.workspace_id !== null && slot.pairing !== null && slot.runner === null);
        want(slot.invitation === null && slot.rotation === null && slot.contexts.length === 0 && slot.runs.length === 0);
    } else {
        want(slot.workspace_id !== null && slot.runner !== null && slot.invitation === null);
        if (slot.pairing !== null) want(slot.pairing.runner_id === slot.runner.runner_id);
        if (phase === 'rotating') {
            want(slot.rotation !== null && slot.rotation.old_runner_key_id === slot.runner.runner_key_id);
        } else {
            want(slot.rotation === null);
        }
    }
}

function checkRegistry(doc, constants) {
    want(exactKeys(doc, [
        'schema_version', 'host_boot_epoch', 'config_generation', 'public_origin', 'backend',
        'management', 'expires_at_ms', 'slots',
    ]));
    want(doc.schema_version === REGISTRY_SCHEMA);
    wantString(doc.host_boot_epoch, RE.epoch);
    wantInt(doc.config_generation, 1, SAFE_INT);
    want(doc.public_origin === 'https://' + constants.host);
    checkSocket(doc.backend);
    want(exactKeys(doc.management, ['address', 'port', 'peer']));
    wantString(doc.management.address, RE.ipv4);
    wantInt(doc.management.port, 1, 65535);
    wantString(doc.management.peer, RE.ipv4);
    wantInt(doc.expires_at_ms, 1, SAFE_INT);
    want(Array.isArray(doc.slots) && doc.slots.length >= 1 && doc.slots.length <= MAX_SLOTS);
    const unique = Object.create(null);
    function once(kind, value) {
        const key = kind + ' ' + value;
        want(!unique[key]);
        unique[key] = true;
    }
    for (const slot of doc.slots) {
        checkSlot(slot);
        once('slot', slot.slot_id);
        once('listener', slot.listener.address + ':' + slot.listener.port);
        once('peer', slot.peer);
        once('namespace', slot.namespace_id);
        if (slot.runner !== null) once('runner', slot.runner.runner_id);
        for (const context of slot.contexts) once('context', context.binding_id);
        for (const run of slot.runs) once('run', run.run_id);
    }
    // The trusted renderer and the reviewed config must agree on every fixed address.
    want(doc.host_boot_epoch === constants.bootEpoch);
    want(doc.backend.address + ':' + doc.backend.port === constants.backend);
    want(doc.management.address + ':' + doc.management.port === constants.management);
    want(doc.management.peer === constants.managementPeer);
}

